def invariants(report: dict) -> List[str]:
    errs: List[str] = []
    for sec in ("metrics", "findings", "diagnoses", "gaps"):
        if not isinstance(report.get(sec), list):
            errs.append("required section %r missing or not a list" % sec)
    for key in ("team", "corpus"):
        if not report.get(key):
            errs.append("required field %r missing" % key)

    for m in report.get("metrics", []):
        if m.get("fidelity") not in ("measured", "judged", "derived"):
            errs.append("metric %s has bad fidelity %r" % (m.get("id"), m.get("fidelity")))
        cov = m.get("coverage") or {}
        if cov.get("value") is None or not cov.get("basis"):
            errs.append("metric %s lacks coverage value/basis" % m.get("id"))
        if m.get("fidelity") == "judged":
            cal = m.get("calibration") or {}
            if cal.get("agreement") is None or cal.get("n") is None:
                errs.append("judged metric %s lacks calibration" % m.get("id"))
            elif cal["agreement"] >= 0.995:
                errs.append("metric %s claims calibration %.3f (>=0.995)" % (m.get("id"), cal["agreement"]))

    gaps = {g.get("ask_id"): g for g in report.get("gaps", [])}
    a11 = gaps.get("A11")
    if not a11:
        errs.append("no A11 gap")
    else:
        if a11.get("verdict") != "NOT_MEASURABLE":
            errs.append("A11 verdict is %r, expected NOT_MEASURABLE" % a11.get("verdict"))
        ev = a11.get("required_event") or {}
        want = {"from_target", "to_target", "reason", "recovered"}
        if ev.get("name") != "failover" or ev.get("grain") != "step" or not want.issubset(set(ev.get("fields") or [])):
            errs.append("A11 required_event incomplete: %r" % ev)

    a04 = [m for m in report.get("metrics", []) if m.get("ask_id") == "A04"]
    if not a04:
        errs.append("A04 has no metric (required ask)")
    elif not any(m.get("fidelity") == "measured" for m in a04):
        errs.append("A04 has no measured metric (got %r)" % [m.get("fidelity") for m in a04])

    if "A09" in gaps:
        if gaps["A09"].get("verdict") != "REQUIRES_NEW_JUDGE":
            errs.append("A09 gap verdict is %r" % gaps["A09"].get("verdict"))
    else:
        a09 = [m for m in report.get("metrics", []) if m.get("ask_id") == "A09"]
        if not a09:
            errs.append("A09 neither gap nor metric")
        elif not any(m.get("fidelity") == "judged" for m in a09):
            errs.append("A09 has no judged metric")

    # cardinality refusal: a customer_ref breakdown must be accompanied by a refusal gap
    if not any(g.get("verdict") == "CARDINALITY_REFUSED" for g in report.get("gaps", [])):
        errs.append("no CARDINALITY_REFUSED gap for custom_dims.customer_ref (budget 200)")
    return errs


def replay_ok(report: dict) -> Dict:
    vers = report.get("verifications") or []
    real = [v for v in vers if str(v.get("replay_run_id", "")).startswith("rp_")]
    improved = [v for v in real if v.get("verdict") == "improved"]
    return {"count": len(real), "improved": len(improved),
            "ok": bool(real) and bool(improved)}


