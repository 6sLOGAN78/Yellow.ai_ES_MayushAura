def test_on_kit(cand: dict, kit: str, tools: str, args) -> Dict:
    name = cand["name"]
    workdir = cand.get("workdir", ".")
    outdir = os.path.join(args.out_root, name, os.path.basename(kit))
    os.makedirs(outdir, exist_ok=True)
    result: Dict = {"kit": os.path.basename(kit), "runs": [], "errors": [], "skipped": []}
    # the candidate never sees the sealed answer key
    run_kit = sanitized_kit(kit, os.path.join(outdir, "candidate-kit"))

    replay_url = ""
    replay_proc = None
    if cand.get("replay", True) and not args.no_replay:
        port = free_port()
        replay_url = "http://127.0.0.1:%d" % port
        replay_proc = subprocess.Popen(
            [sys.executable, os.path.join(tools, "replay", "serve.py"),
             "--kit", kit, "--port", str(port)],
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            start_new_session=True)
        if not wait_http(replay_url + "/health"):
            result["errors"].append("replay server did not start")
            replay_url = ""

    if not (cand.get("replay", True) and not args.no_replay):
        result["skipped"].append("replay (%s)" % ("--no-replay" if args.no_replay else "candidate replay=false"))
    elif not replay_url:
        result["skipped"].append("replay (server unavailable)")
    if args.quick:
        result["skipped"].append("determinism (--quick)")
    if not cand.get("serve"):
        result["skipped"].append("screen (candidate has no serve command)")
    elif args.no_screen:
        result["skipped"].append("screen (--no-screen)")

    try:
        reports = []
        n_runs = 1 if args.quick else 2
        for i in range(n_runs):
            sub = os.path.join(outdir, "run%d" % (i + 1))
            os.makedirs(sub, exist_ok=True)
            out = os.path.join(sub, "loop-report.json")
            cmd = cand["run"].format(kit=run_kit, team="%s-%s" % (name, os.path.basename(kit)),
                                     out=out, outdir=sub, replay_url=replay_url,
                                     port=free_port())
            try:
                rc, log, secs = run(cmd, workdir, args.timeout, env=os.environ.copy())
            except subprocess.TimeoutExpired:
                result["runs"].append({"rc": -9, "seconds": args.timeout, "report": False})
                result["errors"].append("run %d timed out after %ds" % (i + 1, args.timeout))
                return result
            result["runs"].append({"rc": rc, "seconds": round(secs, 1),
                                   "report": os.path.exists(out)})
            if rc != 0 or not os.path.exists(out):
                result["errors"].append("run %d failed rc=%d (%.1fs)\n%s"
                                        % (i + 1, rc, secs, log[-1500:]))
                return result
            reports.append(json.load(open(out)))
        report = reports[0]
        result["report_path"] = os.path.join(outdir, "run1", "loop-report.json")

        # replay provenance: every reported run id must have been issued by the
        # service during this candidate's run, and the reported verdict/before/
        # after must match what the service actually logged (no fabricated evidence)
        logged: Dict[str, dict] = {}
        if replay_url:
            log = fetch_json(replay_url + "/log")
            if log:
                logged = {r.get("run_id"): r for r in log.get("runs", [])}
        result["replay_log_ids"] = len(logged)
        foreign, mismatch = [], []
        pids = {p.get("id") for p in (report.get("prescriptions") or [])}
        for v in (report.get("verifications") or []):
            rid = str(v.get("replay_run_id", ""))
            if not rid.startswith("rp_"):
                continue
            if rid not in logged:
                foreign.append(rid)
                continue
            row = logged[rid]
            for fld in ("verdict", "before", "after"):
                rv, lv = v.get(fld), row.get(fld)
                if rv is None or lv is None:
                    continue
                if isinstance(rv, (int, float)) and isinstance(lv, (int, float)):
                    if abs(float(rv) - float(lv)) > 1e-6:
                        mismatch.append("%s.%s reported=%s logged=%s" % (rid, fld, rv, lv))
                elif rv != lv:
                    mismatch.append("%s.%s reported=%r logged=%r" % (rid, fld, rv, lv))
            if v.get("prescription_id") not in pids:
                mismatch.append("%s.prescription_id %r is not a prescription" % (rid, v.get("prescription_id")))
        result["foreign_replay_ids"] = foreign
        result["replay_mismatches"] = mismatch

        # schema + score
        schema = schema_check.load(os.path.join(tools, "schema", "loop-report.schema.json"))
        result["schema_problems"] = schema_check.problems(report, schema)
        result["schema_backend"] = schema_check.BACKEND
        gt = os.path.join(kit, "ground_truth_SEALED", "ground_truth.json")
        rc, out, _ = run("%s %s --report %s --ground-truth %s --json" % (
            sys.executable, os.path.join(tools, "score.py"),
            os.path.join(outdir, "run1", "loop-report.json"), gt), workdir, args.timeout)
        result["score"] = json.loads(out) if rc == 0 else {"error": out[-800:]}

        scoremod = load_module(os.path.join(tools, "score.py"), "nl_score")
        result["objective"] = objective(report, json.load(open(gt)), scoremod)
        result["invariants"] = invariants(report)
        result["replay"] = replay_ok(report)
        result["determinism"] = (n_runs == 1) or (normalize(reports[0]) == normalize(reports[1]))
        if not result["determinism"]:
            result["errors"].append("two cold runs produced different reports")

        # screen
        if cand.get("serve") and not args.no_screen:
            result["screen"] = screen_test(cand, outdir, report, args)
    finally:
        if replay_proc:
            _terminate(replay_proc)
    return result


def screen_test(cand: dict, outdir: str, report: dict, args) -> Dict:
    report_path = os.path.join(outdir, "run1", "loop-report.json")
    port = free_port()
    cmd = cand["serve"].format(report=report_path, port=port, outdir=outdir)
    proc = subprocess.Popen(cmd, shell=True, cwd=cand.get("workdir", "."),
                            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                            stderr=subprocess.DEVNULL, start_new_session=True)
    base = "http://127.0.0.1:%d" % port
    res = {"started": False, "page": False, "write_back": False, "reason_required": False}
    try:
        if not wait_http(base + "/", timeout=15):
            return res
        res["started"] = True
        import urllib.request
        with urllib.request.urlopen(base + "/", timeout=5) as r:
            body = r.read().decode("utf-8", "ignore")
            res["page"] = r.status == 200 and "<html" in body.lower()
        pres = report.get("prescriptions") or []
        if pres:
            pid = pres[0]["id"]
            st, _ = post_json(base + "/decision",
                              {"prescription_id": pid, "verdict": "accepted",
                               "decided_by": "testbed", "reason": "testbed check"})
            updated = json.load(open(report_path))
            got = [p for p in updated.get("prescriptions", []) if p["id"] == pid]
            res["write_back"] = st == 200 and bool(got and (got[0].get("approval") or {}).get("verdict"))
            st2, _ = post_json(base + "/decision",
                               {"prescription_id": pid, "verdict": "rejected",
                                "decided_by": "testbed", "reason": ""})
            res["reason_required"] = 400 <= st2 < 500
    except Exception as e:  # noqa: BLE001
        res["error"] = str(e)
    finally:
        _terminate(proc)
    return res


