def verdict(res: Dict, require_replay: bool, strict_rules: bool = False,
            lenient_invariants: bool = False) -> Tuple[bool, List[str]]:
    reasons: List[str] = []
    if res.get("errors"):
        return False, res["errors"]
    if res.get("schema_problems"):
        reasons.append("schema: %d problem(s)" % len(res["schema_problems"]))
    for fid, f in res["objective"]["faults"].items():
        if not f.get("clean"):
            reasons.append("fault %s not clean (%s)" % (fid, f))
    for did, d in res["objective"]["decoys"].items():
        if d["false_alarm"]:
            reasons.append("false alarm on %s" % did)
        if not d["explicitly_dismissed"]:
            reasons.append("decoy %s not explicitly dismissed" % did)
    if res["objective"]["strays"]:
        reasons.append("stray findings %s" % res["objective"]["strays"])
    if res["score"].get("sections", {}).get("Honesty", {}).get("score") != 12.0:
        reasons.append("honesty < 12")
    if res.get("invariants") and not lenient_invariants:
        reasons.append("invariants: %s" % res["invariants"][:3])
    if not res.get("determinism", True):
        reasons.append("non-deterministic")
    if res.get("literals") and res["literals"].get("violations"):
        reasons.append("practice literals: %s" % res["literals"]["violations"][:3])
    rules = res.get("rules") or {}
    if rules.get("yardstick_write"):
        reasons.append("Rule 2: code writes to a protected yardstick path: %s"
                       % rules["yardstick_write"][:2])
    if strict_rules and rules.get("llm_deps"):
        reasons.append("Rule 1 audit: LLM dependency referenced: %s" % rules["llm_deps"][:3])
    if res.get("foreign_replay_ids"):
        reasons.append("replay evidence not issued by the service: %s" % res["foreign_replay_ids"])
    if res.get("replay_mismatches"):
        reasons.append("replay evidence does not match the service log: %s"
                       % res["replay_mismatches"][:3])
    if require_replay and not res.get("replay", {}).get("ok"):
        reasons.append("no improved replay verification")
    if res.get("screen") and res["screen"].get("started"):
        if not (res["screen"]["page"] and res["screen"]["write_back"] and res["screen"]["reason_required"]):
            reasons.append("screen checks failed: %s" % res["screen"])
    return (not reasons), reasons


def main() -> int:
    ap = argparse.ArgumentParser()
    default_cands = os.path.join(HERE, "candidates.json")
    if not os.path.exists(default_cands):
        default_cands = os.path.join(HERE, "candidates.example.json")
    ap.add_argument("--candidates", default=default_cands)
    ap.add_argument("--candidate", default=None, help="only run this candidate name")
    ap.add_argument("--tools", default=DEFAULT_TOOLS)
    ap.add_argument("--kits-dir", default=os.path.join(HERE, "kits"))
    ap.add_argument("--out-root", default="/tmp/nexus-testbed/out")
    ap.add_argument("--timeout", type=int, default=600)
    ap.add_argument("--quick", action="store_true", help="one run per kit (skip determinism)")
    ap.add_argument("--no-screen", action="store_true")
    ap.add_argument("--no-replay", action="store_true")
    ap.add_argument("--strict-rules", action="store_true",
                    help="fail on any LLM dependency reference (Rule 1 audit)")
    ap.add_argument("--lenient-invariants", action="store_true",
                    help="do not fail on the extra deliverable invariants (schema+score only)")
    ap.add_argument("--explain", action="store_true",
                    help="print a point ledger: exactly which points were lost and why")
    ap.add_argument("--json-out", default=None)
    ap.add_argument("--matrix-out", default=None, help="write a markdown pass/fail matrix")
    a = ap.parse_args()

    cands = json.load(open(a.candidates))
    if isinstance(cands, dict):
        cands = cands.get("candidates", [])
    if a.candidate:
        cands = [c for c in cands if c["name"] == a.candidate]

    kits = sorted(d for d in glob.glob(os.path.join(a.kits_dir, "*"))
                  if os.path.exists(os.path.join(d, "ground_truth_SEALED", "ground_truth.json")))
    if not kits:
        print("no sealed kits in %s — run testbed/make_corpora.py first" % a.kits_dir)
        return 2

    # a single literal universe across the practice kit and every corpus under
    # test, so practice names are still caught on moved/renamed corpora
    lit_universe = set()
    practice = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(a.tools))), "kit")
    for k in ([practice] if os.path.exists(os.path.join(practice, "catalog.json")) else []) + kits:
        try:
            lit_universe.update(literals_from_kit(k))
        except Exception:
            pass
    all_literals = sorted(lit_universe)

    all_out = {}
    overall_pass = True
    for cand in cands:
        print("\n" + "=" * 78)
        print("CANDIDATE %s   (%s)" % (cand["name"], cand.get("workdir", ".")))
        print("=" * 78)
        rules = rule_scan(cand.get("workdir", "."),
                          cand.get("source_globs", ["**/*.py"]),
                          cand.get("literal_allow_globs", []))
        if rules.get("llm_deps"):
            print("  note: LLM dependency referenced (Rule 1 audit): %s" % rules["llm_deps"][:3])
        if rules.get("yardstick_write"):
            print("  note: Rule 2 risk, writes to protected path: %s" % rules["yardstick_write"][:2])
        cand_out = []
        for kit in kits:
            res = test_on_kit(cand, kit, a.tools, a)
            # literals and rules are candidate-level; attach to each result
            lits = all_literals
            res["literals"] = {
                "checked": lits,
                "violations": literal_scan(cand.get("workdir", "."),
                                           cand.get("source_globs", ["**/*.py"]),
                                           cand.get("literal_allow_globs", []), lits),
            }
            res["rules"] = rules
            res["explain"] = explain_kit(res)
            ok, reasons = verdict(res,
                                  require_replay=bool(cand.get("replay", True)) and not a.no_replay,
                                  strict_rules=a.strict_rules,
                                  lenient_invariants=a.lenient_invariants)
            res["pass"] = ok
            res["reasons"] = reasons
            sc = res.get("score", {})
            print("  %-22s %s  machine=%.1f/55  faults=%s decoys=%s %s" % (
                res["kit"],
                "PASS" if ok else "FAIL",
                sc.get("machine_score", -1),
                "".join("/" if f.get("clean") else "x" for f in res["objective"]["faults"].values()) if res.get("objective") else "?",
                "".join("/" if d.get("clean") else "x" for d in res["objective"]["decoys"].values()) if res.get("objective") else "?",
                "" if ok else "| " + "; ".join(reasons)[:110]))
            if a.explain:
                for ln in res["explain"]:
                    print("        " + ln)
            cand_out.append(res)
            overall_pass = overall_pass and ok
        all_out[cand["name"]] = cand_out

    if a.json_out:
        json.dump(all_out, open(a.json_out, "w"), indent=2, default=str)
        print("\nwrote %s" % a.json_out)

    if a.matrix_out:
        write_matrix(a.matrix_out, all_out)
        print("wrote %s" % a.matrix_out)

    print("\nOVERALL: %s" % ("ALL CANDIDATES PASS" if overall_pass else "FAILURES PRESENT"))
    return 0 if overall_pass else 1


def write_matrix(path: str, all_out: Dict) -> None:
    kits = sorted({r["kit"] for rows in all_out.values() for r in rows})
    candidates = list(all_out.keys())
    lines = ["# Testbed matrix", "", "| corpus | " + " | ".join(candidates) + " |",
             "|---" * (len(candidates) + 1) + "|"]
    for kit in kits:
        cells = []
        for cand in candidates:
            row = next((r for r in all_out[cand] if r["kit"] == kit), None)
            if row is None:
                cells.append("n/a")
            else:
                mark = "PASS" if row.get("pass") else "FAIL"
                sc = row.get("score", {}).get("machine_score")
                cells.append("%s (%.1f)" % (mark, sc) if isinstance(sc, (int, float)) else mark)
        lines.append("| %s | %s |" % (kit, " | ".join(cells)))
    lines.append("")
    lines.append("Faults F1/F2/F3 and decoys D1/D2/D3 are marked per corpus in the JSON output.")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


