#!/usr/bin/env python3
"""General testbed for Nexus Loop candidate solutions.

It does not assume any particular implementation. A candidate is described by a
command template and tested, unattended, against several held-out (sealed)
corpora generated by the kit itself. For each corpus it:

  1. starts the kit's replay service and passes its URL to the candidate;
  2. runs the candidate cold (twice, to check determinism) with stdin closed;
  3. requires a schema-valid ``loop-report.json`` from one command;
  4. scores it with the organiser's own ``score.py`` against the held-out key;
  5. checks the faults, the decoys, stray findings, and the deliverable
     invariants the scorer does not enforce;
  6. scans the candidate source for practice literals (generality);
  7. exercises the decision screen and its write-back (if the candidate serves one).

A candidate passes only when every corpus yields: every fault found with the
right cohort and cause and no detection lag, every decoy not falsely flagged,
no strays, honesty = 12, schema-valid, determinism, no practice literals, a
working approval write-back, and a real replay verification when a replay URL
was provided.

Usage:
    python3 testbed/evaluate.py --candidates testbed/candidates.json
    python3 testbed/evaluate.py --candidate anupam-pr1 --quick
"""
