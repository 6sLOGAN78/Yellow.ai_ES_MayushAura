def load_module(path: str, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def free_port() -> int:
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    return port


def sanitized_kit(kit: str, dest: str) -> str:
    """A copy of the kit for the candidate with the sealed answer keys removed.

    The candidate must not be able to read `ground_truth*`; a real copy (not
    symlinks) keeps the path self-contained, so `realpath` cannot walk back to
    the key either. The key is passed only to the scorer."""
    if os.path.isdir(dest):
        return dest
    shutil.copytree(kit, dest,
                    ignore=shutil.ignore_patterns("ground_truth", "ground_truth_SEALED"))
    return dest


def run(cmd: str, cwd: str, timeout: int, env=None) -> Tuple[int, str, float]:
    t0 = time.time()
    p = subprocess.run(cmd, shell=True, cwd=cwd, stdin=subprocess.DEVNULL,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                       text=True, timeout=timeout, env=env)
    return p.returncode, p.stdout, time.time() - t0


def _terminate(proc) -> None:
    import signal
    try:
        pgid = os.getpgid(proc.pid)
    except Exception:
        pgid = None
    try:
        if pgid is not None and pgid != os.getpgid(0):
            os.killpg(pgid, signal.SIGTERM)
        else:
            proc.terminate()
    except Exception:
        try:
            proc.terminate()
        except Exception:
            pass
    try:
        proc.wait(timeout=5)
    except Exception:
        try:
            proc.kill()
        except Exception:
            pass


def wait_http(url: str, timeout: float = 20.0) -> bool:
    import urllib.request
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=1) as r:
                if r.status == 200:
                    return True
        except Exception:
            time.sleep(0.3)
    return False


def post_json(url: str, payload: dict, timeout: float = 10.0) -> Tuple[int, str]:
    import urllib.request
    import urllib.error
    req = urllib.request.Request(url, data=json.dumps(payload).encode(),
                                 headers={"Content-Type": "application/json"}, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, r.read().decode()
    except urllib.error.HTTPError as e:  # type: ignore[attr-defined]
        return e.code, e.read().decode()


def normalize(report: dict) -> dict:
    """Drop volatile fields so two runs can be compared for determinism."""
    def walk(o):
        if isinstance(o, dict):
            return {k: walk(v) for k, v in o.items()
                    if k not in ("generated_at", "at", "generated", "out", "team",
                                 "runs_used", "run_budget")}
        if isinstance(o, list):
            return [walk(x) for x in o]
        return o
    return walk(report)


